import { InvalidArgumentError } from './errors.js';
import type { SecretBytes } from './keys.js';

/** The ML-DSA levels that have a standards-mode (bare FIPS 204) signer. */
export type StandardAlgorithm = 'ML-DSA-44' | 'ML-DSA-65' | 'ML-DSA-87';

/** @internal */
export const STANDARD_ALGORITHMS: readonly StandardAlgorithm[] = ['ML-DSA-44', 'ML-DSA-65', 'ML-DSA-87'];

/** Length of the secret seed, in bytes (FIPS 204 `xi`). */
export const STANDARD_SEED_LENGTH = 32;

/**
 * A standards-mode ML-DSA key pair: the FIPS 204 public key and the 32-byte seed it is derived from.
 *
 * The seed is FIPS 204's native secret-key form (the expanded secret key is derived from it), and it is what RFC 9964 stores in the
 * private AKP JWK. It is held in WebAssembly memory and wiped by {@link StandardKeyPair.free} (or `using`).
 *
 * **Interoperability.** A standard FIPS 204 signature made with this key verifies anywhere (quantum-safe-py `verify_raw`, any FIPS 204
 * library). The reverse has one limit: a secret key that quantum-safe-py generated through liboqs is a 4,032-byte *expanded* key from
 * which no seed can be recovered, so quantum-safe-ts cannot sign with it. It can verify everything that key signs. Keys generated by
 * quantum-safe-py's `cryptography` backend, or by this class, are seed keys and work in both libraries.
 *
 * @example
 * ```ts
 * const signer = new Sign('ML-DSA-65');
 * using pair = signer.generateStandardKeyPair();
 * const sig = signer.signRaw(utf8('release 1.2.3'), pair, { context: utf8('myapp-release') });
 * signer.verifyRaw(utf8('release 1.2.3'), sig, pair.publicKey, { context: utf8('myapp-release') });
 * ```
 */
export class StandardKeyPair {
  /** `ML-DSA-44`, `ML-DSA-65` or `ML-DSA-87`. */
  readonly algorithm: StandardAlgorithm;
  /** FIPS 204 encoded public key (1312 / 1952 / 2592 bytes). Not secret. */
  readonly publicKey: Uint8Array;
  readonly #seed: SecretBytes;

  /** @internal Use `Sign.generateStandardKeyPair()` or `Sign.standardKeyPairFromSeed()`. */
  constructor(algorithm: StandardAlgorithm, publicKey: Uint8Array, seed: SecretBytes) {
    this.algorithm = algorithm;
    this.publicKey = publicKey;
    this.#seed = seed;
  }

  /** @internal */
  get _seed(): SecretBytes {
    return this.#seed;
  }

  /** Copies the 32-byte seed out of WebAssembly memory. **Wipe the copy after use** (`seed.fill(0)`). */
  exportSeed(): Uint8Array {
    return this.#seed.exportBytes();
  }

  /** Wipes the seed. Using the pair afterwards throws. */
  free(): void {
    this.#seed.free();
  }
  [Symbol.dispose](): void {
    this.free();
  }

  toString(): string {
    return `StandardKeyPair(${this.algorithm}, <seed redacted>)`;
  }
  toJSON(): { algorithm: StandardAlgorithm; publicKey: string } {
    return { algorithm: this.algorithm, publicKey: '<public key omitted>' };
  }
}

/** @internal */
export function checkStandardAlgorithm(algorithm: string): StandardAlgorithm {
  if (!(STANDARD_ALGORITHMS as readonly string[]).includes(algorithm)) {
    throw new InvalidArgumentError(`A standard FIPS 204 signature is offered for ${STANDARD_ALGORITHMS.join(', ')}, not '${algorithm}'.`);
  }
  return algorithm as StandardAlgorithm;
}
